import { NextResponse } from "next/server";
import path from "node:path";
import { session, SESSION_ENDED } from "@/lib/access";
import { tooMany } from "@/lib/rate";
import { fetchableUrl, ownsMedia, saveMedia } from "@/lib/media";
import { type BuildClip, build, captions, download, frameSize, probe, segLen, workdir } from "@/lib/montage";
import { normalizeStyle } from "@/lib/caption-style";
import { escalar, escalarPalabras, escalarTextos, limpiarProyecto, pasadaAudio, pasadaTextos, textosAss } from "@/lib/editor";
import { publicError } from "@/lib/public-error";
import type { Word } from "@/lib/textmatch";
import { hasPaid } from "@/lib/regalo";

export const dynamic = "force-dynamic";
export const maxDuration = 300;

// Renders the editor's project: the cuts in their order and trims, subtitles, texts on top, voice and music,
// in the chosen format. Free (nothing is generated by AI), 1–3 minutes. Editing is free for everyone (owner's
// plan, 25 Oct 2026); accounts that never paid (no Pack Prueba, no plan) export with the «Creads IA» mark. The previous video is kept in the ad's
// versions; the new one becomes the ad's finished video.

type Settings = Record<string, unknown> & { review?: { clipId: string; url?: string; words: Word[] }[]; captions?: unknown; editorCaptions?: unknown; versiones?: string[] };
interface ClipRow { id: string; idx: number; url: string | null; status: string; text: string | null }

export async function POST(req: Request, ctx: { params: Promise<{ id: string }> }) {
  const s = await session(req);
  if (!s) return NextResponse.json({ error: SESSION_ENDED }, { status: 401 });
  const limited = await tooMany("heavy", s.user.id);
  if (limited) return limited;
  const id = (await ctx.params).id;
  const ws = s.user.workspace;
  try {
    const ad = (await s.db.get("ads", id).catch(() => null)) as { id: string; final_url: string | null; settings: Settings | null } | null;
    if (!ad) return NextResponse.json({ error: "No encontré ese anuncio." }, { status: 404 });
    const clips = ((await s.db.list("clips", `ad_id=eq.${id}&order=idx.asc`)) as unknown as ClipRow[]).filter((c) => c.status === "done" && c.url);
    const byId = new Map(clips.map((c) => [c.id, c]));
    const b = await req.json().catch(() => null);
    const p = limpiarProyecto(b?.proyecto, new Set(byId.keys()));
    if (!p.cortes.length) return NextResponse.json({ error: "Deja al menos un corte en la línea de tiempo." }, { status: 400 });
    if (p.musica && !ownsMedia(p.musica.url, ws)) p.musica = null;
    const st = ad.settings ?? {};
    const dir = await workdir(`${id}-ed`);

    // each clip downloaded once, even if it's used twice
    const files = new Map<string, { file: string; dur: number; audio: boolean }>();
    for (const c of p.cortes) {
      if (files.has(c.clipId)) continue;
      const row = byId.get(c.clipId)!;
      const file = path.join(dir, `e${row.idx}.mp4`);
      await download(await fetchableUrl(row.url!, ws), file);
      const pr = await probe(file);
      files.set(c.clipId, { file, dur: pr.dur, audio: pr.audio });
    }
    const parts: BuildClip[] = p.cortes.map((c) => {
      const f = files.get(c.clipId)!;
      const a = Math.min(Math.max(0, c.a), Math.max(0, f.dur - 0.3));
      return { file: f.file, a, b: Math.min(f.dur, Math.max(a + 0.3, c.b)), audio: f.audio };
    });

    // the words on the new timeline (from the review's transcript of each clip)
    let offset = 0;
    const timeline: Word[] = [];
    p.cortes.forEach((c, i) => {
      const row = byId.get(c.clipId)!;
      const words = st.review?.find((r) => r.clipId === row.id && r.url === row.url)?.words ?? [];
      const seg = parts[i];
      // apply the editor's subtitle spelling fixes (same «clipId:index» key the editor shows and stores)
      words.forEach((w, j) => {
        if (!(w.s >= seg.a - 0.05 && w.e <= seg.b + 0.3)) return;
        const text = p.subCorr?.[`${row.id}:${j}`] ?? w.w;
        if (!text) return;
        timeline.push({ w: text, s: Math.max(0, w.s - seg.a) + offset, e: Math.max(0, Math.min(w.e, seg.b) - seg.a) + offset });
      });
      offset += segLen(seg);
    });
    const [W, H] = frameSize(p.formato);
    // the sped-up output timeline: the picture runs setpts=PTS/velocidad, so every text, subtitle and the music
    // is placed at its scaled time (source second / velocidad) and the reported length shrinks the same way.
    const vel = p.velocidad;
    const salida = escalar(offset, vel); // final duration after speed-up
    const style = normalizeStyle(st.editorCaptions ?? st.captions ?? undefined); // the editor's own pick wins
    const cap = p.subtitulos && timeline.length ? captions(escalarPalabras(timeline, vel), W, H, p.formato, style, salida, []) : null;
    let bytes: Uint8Array | Buffer = await build(dir, parts, p.formato, cap?.ass ?? null, vel);
    const marca = ws !== "main" && !(await hasPaid(ws).catch(() => false));
    const textosBase = escalarTextos(p.textos, vel);
    const textos = marca ? [...textosBase, { id: "sello", texto: "Hecho con Creads IA", desde: 0, hasta: salida + 1, x: 30, y: 7, tam: 4.5, color: "#FFFFFF", fondo: "#8A5CFF", fuente: "Montserrat ExtraBold" as const, animacion: "ninguna" as const }] : textosBase;
    if (textos.length) bytes = await pasadaTextos(dir, bytes, textosAss(textos, W, H));
    if (p.musica || p.vozVol !== 100) {
      const music = p.musica ? path.join(dir, "musica.audio") : null;
      if (music && p.musica) await download(await fetchableUrl(p.musica.url, ws), music);
      bytes = await pasadaAudio(dir, bytes, music, p.vozVol, p.musica?.vol ?? 0, salida);
    }

    const url = await saveMedia(ws, "finals", bytes, "video/mp4", `${id}-ed-${Date.now()}.mp4`);
    const versiones = [...(st.versiones ?? []), ...(ad.final_url ? [ad.final_url] : [])].slice(-10);
    await s.db.update("ads", id, { final_url: url, status: "done", settings: { ...st, editor: p, versiones, duration: Math.round(salida * 10) / 10 } });
    return NextResponse.json({ url, segundos: Math.round(salida * 10) / 10 });
  } catch (err) {
    return NextResponse.json({ error: publicError(err, "No se pudo exportar el video.") }, { status: 502 });
  }
}
